<?php

/**
 * Storage for the DPD RO API cache and the optional debug log.
 *
 * - Credentials are masked before anything is logged.
 * - Request logging is OFF by default. When enabled (Advanced settings >
 *   Debug log) it goes through the WooCommerce logger, which handles size
 *   rotation, retention, unguessable file names, and is viewable under
 *   WooCommerce > Status > Logs (source "dpdro").
 * - The cache folder lives under wp-content and may be reachable over HTTP,
 *   so every folder gets an index.php and a deny-all .htaccess. Some servers
 *   (e.g. OpenLiteSpeed) ignore per-folder .htaccess files, which is why the
 *   cache files keep unguessable names and nothing secret or listable is
 *   written here in plain text.
 * - Cache keys include a 10-minute window, so day folders older than today
 *   are never read again; a daily WP-Cron job deletes them.
 */

if (!defined('ABSPATH')) {
	exit;
}

class DpdroStorage
{
	const LOG_SOURCE    = 'dpdro';
	const CLEANUP_HOOK  = 'dpdro_storage_cleanup';
	const SETTING_DEBUG = 'debug_log';
	const MASK          = '*****';

	/**
	 * Lower-cased keys whose values must never reach a log.
	 */
	private static $secretKeys = array('username', 'password');

	/**
	 * Debug flag, memoized for the current request.
	 */
	private static $debugEnabled = null;

	/**
	 * Folders already created and protected during the current request.
	 */
	private static $readyDirs = array();

	/**
	 * Hook the daily cleanup and the boot routine.
	 */
	public static function register()
	{
		add_action(self::CLEANUP_HOOK, array(__CLASS__, 'cleanup'));
		add_action('init', array(__CLASS__, 'boot'));
	}

	/**
	 * Runs on every request (cheap): removes the legacy plain-text log right
	 * away instead of waiting for cron, and makes sure the cleanup is scheduled.
	 */
	public static function boot()
	{
		self::removeLegacyLog(self::baseDir());

		if (function_exists('wp_next_scheduled') && !wp_next_scheduled(self::CLEANUP_HOOK)) {
			wp_schedule_event(time(), 'daily', self::CLEANUP_HOOK);
		}
	}

	/**
	 * Remove the scheduled cleanup (plugin deactivation / uninstall).
	 */
	public static function unscheduleCleanup()
	{
		if (function_exists('wp_clear_scheduled_hook')) {
			wp_clear_scheduled_hook(self::CLEANUP_HOOK);
		}
	}

	/**
	 * Base storage folder: wp-content/dpdro.
	 */
	public static function baseDir()
	{
		$dir = defined('PLUGIN_LOGS_DIR_DPDRO')
			? PLUGIN_LOGS_DIR_DPDRO
			: dirname(__DIR__, 3) . '/dpdro'; // uninstall.php runs without the plugin loaded
		// PLUGIN_LOGS_DIR_DPDRO is "<plugin>/../../dpdro". wp_mkdir_p() refuses
		// any path containing "../", so with it as is the daily cache folders
		// were never created and every DPD API request returned nothing
		// (3.3.12 - 3.3.13). Resolve the ".." segments first.
		return self::normalizePath($dir);
	}

	/**
	 * Resolve "." and ".." segments without touching the disk (the folder may
	 * not exist yet, so realpath() cannot be used).
	 */
	public static function normalizePath($path)
	{
		$path = str_replace('\\', '/', $path);
		$prefix = '';
		if (preg_match('#^([A-Za-z]:)?/#', $path, $m)) {
			$prefix = $m[0];
			$path = substr($path, strlen($prefix));
		}
		$parts = array();
		foreach (explode('/', $path) as $part) {
			if ($part === '' || $part === '.') {
				continue;
			}
			if ($part === '..' && $parts && end($parts) !== '..') {
				array_pop($parts);
			} elseif ($part === '..' && $prefix !== '') {
				continue; // cannot go above the root
			} else {
				$parts[] = $part;
			}
		}
		return str_replace('/', DIRECTORY_SEPARATOR, $prefix . implode('/', $parts));
	}

	/**
	 * Today's cache folder, created and protected on demand.
	 */
	public static function cacheDir($today = null)
	{
		$base = self::baseDir();
		$dir = $base . DIRECTORY_SEPARATOR . ($today ? $today : date('Y-m-d'));
		self::ensureDir($base);
		self::ensureDir($dir);
		return $dir;
	}

	/**
	 * Create a folder (if missing) and drop the protection files into it.
	 */
	public static function ensureDir($dir)
	{
		if (isset(self::$readyDirs[$dir])) {
			return true;
		}
		if (!is_dir($dir)) {
			if (function_exists('wp_mkdir_p')) {
				wp_mkdir_p($dir);
			}
			if (!is_dir($dir)) {
				@mkdir($dir, 0755, true);
			}
		}
		if (!is_dir($dir)) {
			return false;
		}
		self::protect($dir);
		self::$readyDirs[$dir] = true;
		return true;
	}

	/**
	 * Block directory listing and HTTP access to a folder.
	 */
	public static function protect($dir)
	{
		$index = $dir . DIRECTORY_SEPARATOR . 'index.php';
		if (!file_exists($index)) {
			@file_put_contents($index, "<?php\n// Silence is golden.\n");
		}
		$htaccess = $dir . DIRECTORY_SEPARATOR . '.htaccess';
		if (!file_exists($htaccess)) {
			@file_put_contents($htaccess, self::htaccessRules());
		}
	}

	/**
	 * Deny-all rules for Apache 2.4 and 2.2.
	 */
	public static function htaccessRules()
	{
		return "# Generated by DPD RO. These files are read by PHP only, never over HTTP.\n"
			. "<IfModule mod_authz_core.c>\n"
			. "\tRequire all denied\n"
			. "</IfModule>\n"
			. "<IfModule !mod_authz_core.c>\n"
			. "\tOrder deny,allow\n"
			. "\tDeny from all\n"
			. "</IfModule>\n";
	}

	/**
	 * Return a copy of $data with every credential value replaced by MASK.
	 * Keys are matched case-insensitively, at any depth.
	 */
	public static function maskSecrets($data)
	{
		if (is_object($data)) {
			$data = (array) $data;
		}
		if (!is_array($data)) {
			return $data;
		}
		foreach ($data as $key => $value) {
			if (is_string($key) && in_array(strtolower($key), self::$secretKeys, true)) {
				$data[$key] = self::MASK;
			} elseif (is_array($value) || is_object($value)) {
				$data[$key] = self::maskSecrets($value);
			}
		}
		return $data;
	}

	/**
	 * Whether the "Debug log" setting is on. Off when the setting is missing.
	 */
	public static function isDebugEnabled()
	{
		if (self::$debugEnabled === null) {
			self::$debugEnabled = false;
			if (class_exists('DataSettings')) {
				global $wpdb;
				$settings = new DataSettings($wpdb);
				self::$debugEnabled = ((string) $settings->getSetting(self::SETTING_DEBUG) === '1');
			}
		}
		return self::$debugEnabled;
	}

	/**
	 * Write a masked entry to the WooCommerce log, only when debugging is on.
	 *
	 * Logged at "info" so a site-wide WooCommerce level threshold does not
	 * silently drop entries the merchant explicitly switched on.
	 */
	public static function log(array $entry)
	{
		if (!self::isDebugEnabled() || !function_exists('wc_get_logger')) {
			return false;
		}
		$masked = self::maskSecrets($entry);
		$message = function_exists('wp_json_encode') ? wp_json_encode($masked) : json_encode($masked);
		wc_get_logger()->info($message, array('source' => self::LOG_SOURCE));
		return true;
	}

	/**
	 * Daily WP-Cron callback.
	 */
	public static function cleanup()
	{
		return self::purge(self::baseDir(), date('Y-m-d'));
	}

	/**
	 * Delete the legacy log, every day folder except $today, and the
	 * cache-key log older versions wrote into each day folder.
	 */
	public static function purge($baseDir, $today)
	{
		$result = array(
			'legacy_log_removed' => false,
			'removed_dirs'       => array(),
		);
		if (!is_dir($baseDir)) {
			return $result;
		}

		$result['legacy_log_removed'] = self::removeLegacyLog($baseDir);

		foreach (scandir($baseDir) as $entry) {
			if ($entry === '.' || $entry === '..' || $entry === $today) {
				continue;
			}
			$path = $baseDir . DIRECTORY_SEPARATOR . $entry;
			if (is_dir($path) && !is_link($path) && preg_match('/^\d{4}-\d{2}-\d{2}$/', $entry)) {
				self::removeTree($path);
				unset(self::$readyDirs[$path]);
				$result['removed_dirs'][] = $entry;
			}
		}

		$todayDir = $baseDir . DIRECTORY_SEPARATOR . $today;
		$cacheKeyLog = $todayDir . DIRECTORY_SEPARATOR . '000_cache_log';
		if (is_file($cacheKeyLog)) {
			@unlink($cacheKeyLog);
		}

		self::protect($baseDir);
		if (is_dir($todayDir)) {
			self::protect($todayDir);
		}
		return $result;
	}

	/**
	 * Delete the whole storage folder (uninstall). Refuses anything that is
	 * not a real folder named "dpdro".
	 */
	public static function removeAll($baseDir = null)
	{
		$baseDir = $baseDir ? rtrim($baseDir, '/\\') : self::baseDir();
		if (basename($baseDir) !== 'dpdro' || !is_dir($baseDir) || is_link($baseDir)) {
			return false;
		}
		self::removeTree($baseDir);
		self::$readyDirs = array();
		return !is_dir($baseDir);
	}

	/**
	 * Clear per-request memoization (used by the standalone tests).
	 */
	public static function resetRuntimeState()
	{
		self::$debugEnabled = null;
		self::$readyDirs = array();
	}

	/**
	 * Versions up to 3.3.11 wrote every API request, credentials included,
	 * in plain text to wp-content/dpdro/logs.json.
	 */
	private static function removeLegacyLog($baseDir)
	{
		$file = $baseDir . DIRECTORY_SEPARATOR . 'logs.json';
		if (!is_file($file)) {
			return false;
		}
		@unlink($file);
		return !file_exists($file);
	}

	/**
	 * Recursively delete a folder without following symlinks.
	 */
	private static function removeTree($dir)
	{
		$items = new RecursiveIteratorIterator(
			new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS),
			RecursiveIteratorIterator::CHILD_FIRST
		);
		foreach ($items as $item) {
			$path = $item->getPathname();
			if ($item->isDir() && !$item->isLink()) {
				@rmdir($path);
			} else {
				@unlink($path);
			}
		}
		@rmdir($dir);
	}
}
